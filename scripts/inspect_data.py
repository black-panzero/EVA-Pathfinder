#!/usr/bin/env python3
"""Print a data inspection report for the prepared study area (and write docs/DATA_INSPECTION.md)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.domain.terrain import TerrainGrid  # noqa: E402


def main() -> None:
    area = json.loads((ROOT / "config/study_area.json").read_text())
    d = ROOT / "data/processed" / area["study_area_id"]
    m = json.loads((d / "manifest.json").read_text())
    g = TerrainGrid.from_geotiff(d / "dem_crop.tif", "dem")
    z = g.elevation_m
    sci = json.loads((d / "science_sites.json").read_text())
    lines = [
        "# Data inspection report", "",
        f"Generated by `scripts/inspect_data.py` from `{d.relative_to(ROOT)}` (prepared {m['created_at']}).", "",
        "## Study area", "",
        f"- CRS: {m['crs']['name']} (sphere R = {m['crs']['sphere_radius_m']:.0f} m), {m['crs']['longitude_convention']}, {m['crs']['latitude_convention']}",
        f"- Grid: {g.width} x {g.height} cells at {g.res_m:.0f} m projected ({g.width * g.res_m / 1000:.1f} x {g.height * g.res_m / 1000:.1f} km projected)",
        f"- Origin easting {m['grid']['origin_easting_m']:.3f} m, northing top {m['grid']['origin_northing_top_m']:.3f} m",
        f"- Longitude {m['grid']['lon_range_deg'][0]:.5f} to {m['grid']['lon_range_deg'][1]:.5f} °E; latitude {m['grid']['lat_range_deg'][0]:.5f} to {m['grid']['lat_range_deg'][1]:.5f} °N",
        f"- East-west ground scale factor at centre: {m['crs']['east_west_scale_factor_at_center']} (ground m per projected m)",
        f"- Window in source DEM: {m['grid']['dem_window_in_source']}", "",
        "## Elevation (CTX DTM, metres relative to geoid)", "",
        f"- Valid fraction: {np.isfinite(z).mean() * 100:.3f} %",
        f"- Min / mean / max: {np.nanmin(z):.2f} / {np.nanmean(z):.2f} / {np.nanmax(z):.2f} m",
        f"- Slope p50 / p95 / max: {np.nanpercentile(g.slope_deg, 50):.2f} / {np.nanpercentile(g.slope_deg, 95):.2f} / {np.nanmax(g.slope_deg):.2f} °",
        f"- Cells steeper than 15°: {(g.slope_deg > 15).mean() * 100:.2f} %", "",
        "Sample DEM values (cell centre, row/col → elevation):", "",
    ]
    for r, c in [(0, 0), (g.height // 2, g.width // 2), (g.height - 1, g.width - 1), (112, 100), (60, 300)]:
        lon, lat = g.cell_lonlat(r, c)
        lines.append(f"- row {r}, col {c} ({lat:.5f}°N, {lon:.5f}°E): {z[r, c]:.2f} m, slope {g.slope_deg[r, c]:.2f}°")
    al = m["alignment"]
    ev = al["dem_vs_rover_elevation"]
    rc = al["registration_check"]
    lines += ["", "## Alignment", "",
              f"- Orthomosaic vs DEM: same CRS; grid origin difference {al['ortho_dem_grid_origin_difference_m']} m; ortho crop {al['ortho_crop_px']} px at {al['ortho_pixel_m']} m",
              f"- DEM vs {ev['n']} Perseverance end-of-drive geoid elevations: median DEM−rover {ev['median_dem_minus_rover_m']} m, median |Δ| {ev['median_abs_m']} m, 5–95 % {ev['p05_m']} to {ev['p95_m']} m",
              f"- Gradient cross-correlation: best shift {rc['best_shift_cells']} cells, r = {rc['best_correlation']} (zero shift r = {rc['zero_shift_correlation']}). Shadow direction biases this check, so it is inconclusive.",
              f"- Geology: {al['geology_status']}. {al['geology_note']}", "",
              "## Waypoints (resolved from NASA rover localization records)", ""]
    for p in [sci["habitat"], *sci["sites"]]:
        lines.append(f"- {p['name']}: x {p['x_m']} m, y {p['y_m']} m; {p['lat_deg']:.6f}°N {p['lon_deg']:.6f}°E; sol {p['sol']}, site {p['site']}, drive {p['drive']}; rover geoid elev {p['rover_elev_geoid_m']} m vs DEM {p['dem_elev_m']} m")
    lines += ["", "## Artifacts", "", "| artifact | evidence level | sha256 (first 16) | limitations |", "|---|---|---|---|"]
    for a in m["artifacts"]:
        lines.append(f"| {a['file']} | {a['evidence_level']} | {(a['checksum_sha256'] or '')[:16]} | {a['limitations']} |")
    lines += ["", "## Source status", ""]
    for sid, st in m["source_status"].items():
        lines.append(f"- {sid}: {st['status']}" + "".join(f"\n  - {f['path']} sha256 {f['sha256']}" for f in st.get("files", [])))
    text = "\n".join(lines) + "\n"
    (ROOT / "docs/DATA_INSPECTION.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
